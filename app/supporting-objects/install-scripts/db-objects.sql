  CREATE OR REPLACE FORCE EDITIONABLE VIEW "BICC_FILES_V" ("FILE_NAME", "FILE_SIZE", "FILE_SIZE_KB", "LAST_MODIFIED", "BATCH_ID", "FILE_TIMESTAMP", "LOAD_TYPE", "LOADER_AVAILABLE") AS 
  WITH o AS (
  SELECT
    regexp_substr(object_name, '[^/]+$') AS file_name,
    bytes                               AS file_size,
    last_modified
  FROM table(
    dbms_cloud.list_objects(
      credential_name => 'OBJ_STORE_CRED_JK',
      location_uri    => 'https://objectstorage.us-ashburn-1.oraclecloud.com/n/idlhcuqzdx2c/b/SCI_Conversion/o/'
    )
  )
  WHERE lower(object_name) LIKE '%.zip'
),
x AS (
  SELECT
    file_name,
    file_size,
    round(file_size / 1024, 2) AS file_size_kb,
    last_modified,
    regexp_substr(file_name, 'batch(\d+)', 1, 1, 'i', 1) AS batch_id,
    to_timestamp(
      regexp_substr(file_name, '-(\d{8}_\d{6})\.zip', 1, 1, 'i', 1),
      'YYYYMMDD_HH24MISS'
    ) AS file_timestamp
  FROM o
)
SELECT
  x.file_name,
  x.file_size,
  x.file_size_kb,
  x.last_modified,
  x.batch_id,
  x.file_timestamp,
  coalesce(m.load_type, 'UNMAPPED') AS load_type,
  CASE
    WHEN m.load_type IS NOT NULL THEN 'Y'
    ELSE 'N'
  END AS loader_available
