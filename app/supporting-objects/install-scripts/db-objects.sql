  --------------------------------------------------------------------
  procedure profile_table (
    p_table_name   in varchar2,
    p_all_thresh   in number   default 6,
    p_sample_n     in number   default 6
  ) is
    l_tname    varchar2(128) := upper(trim(p_table_name));
    l_total    number;
    l_nonblank number;
    l_distinct number;
    l_null_pct number;
    l_sql      clob;
    l_vals_sql clob;
    l_vals     varchar2(4000);
  begin
    -- Validate table exists in current schema
    declare
      l_dummy number;
    begin
      select 1 into l_dummy
      from   user_tables
      where  table_name = l_tname
      and    rownum = 1;
    exception
      when no_data_found then
        raise_application_error(-20001, 'Table not found: ' || l_tname);
    end;

    execute immediate 'select count(*) from "' || l_tname || '"' into l_total;

    -- Remove previous profile for this table
    delete from column_profile where table_name = l_tname;

    for c in (
      select column_name, data_type
      from   user_tab_columns
      where  table_name = l_tname
        and  data_type not in ('CLOB','BLOB','LONG','LONG RAW', 'RAW')
      order  by column_id
    ) loop
      l_vals := null;

      if c.data_type in ('CHAR','VARCHAR2','NCHAR','NVARCHAR2') then
        ---------------------------------------------------------
        -- String columns: trim blanks before counting
        ---------------------------------------------------------
        l_sql :=
          'select '||
          '  sum(case when nullif(trim("'||c.column_name||'"),'''') is not null then 1 else 0 end),'||
          '  count(distinct nullif(trim("'||c.column_name||'"),'''')) '||
          'from "'||l_tname||'"';
        execute immediate l_sql into l_nonblank, l_distinct;

        if nvl(l_nonblank,0) = 0 then continue; end if;

        if l_distinct <= p_all_thresh then
          l_vals_sql :=
            'select listagg(val,'', '') within group (order by val) '||
            'from (select distinct trim("'||c.column_name||'") as val '||
            '      from "'||l_tname||'"'||
            '      where nullif(trim("'||c.column_name||'"),'''') is not null)';
        else
          l_vals_sql :=
            'select listagg(val,'', '') within group (order by val) '||
            'from (select val from ('||
            '        select distinct trim("'||c.column_name||'") as val '||
            '        from "'||l_tname||'"'||
            '        where nullif(trim("'||c.column_name||'"),'''') is not null'||
            '      ) order by val fetch first '||p_sample_n||' rows only)';
        end if;
        execute immediate l_vals_sql into l_vals;

      else
        ---------------------------------------------------------
        -- NUMBER / DATE / TIMESTAMP columns
        ---------------------------------------------------------
        l_sql :=
          'select count("'||c.column_name||'"), count(distinct "'||c.column_name||'") '||
          'from "'||l_tname||'"';
        execute immediate l_sql into l_nonblank, l_distinct;

        if nvl(l_nonblank,0) = 0 then continue; end if;

        if l_distinct <= p_all_thresh then
          l_vals_sql :=
            'select listagg(val,'', '') within group (order by val) '||
            'from (select distinct to_char("'||c.column_name||'") as val '||
            '      from "'||l_tname||'"'||
            '      where "'||c.column_name||'" is not null)';
        else
          l_vals_sql :=
            'select listagg(val,'', '') within group (order by val) '||
            'from (select val from ('||
            '        select distinct to_char("'||c.column_name||'") as val '||
            '        from "'||l_tname||'"'||
            '        where "'||c.column_name||'" is not null'||
            '      ) order by val fetch first '||p_sample_n||' rows only)';
        end if;
        execute immediate l_vals_sql into l_vals;
      end if;

      l_null_pct := case
                      when l_total > 0
                      then round((l_total - nvl(l_nonblank,0)) / l_total * 100, 2)
                      else 0
                    end;

      insert into column_profile
        (table_name, column_name, total_rows, nonblank_count,
         distinct_count, null_pct, sample_values)
      values
        (l_tname, c.column_name, l_total, l_nonblank,
         l_distinct, l_null_pct, l_vals);

    end loop;

    commit;
  end profile_table;

  --------------------------------------------------------------------
  procedure profile_tables (
    p_table_names  in sys.odcivarchar2list,
    p_all_thresh   in number   default 6,
    p_sample_n     in number   default 6
  ) is
  begin
    for i in 1 .. p_table_names.count loop
      profile_table(
        p_table_name => p_table_names(i),
        p_all_thresh => p_all_thresh,
        p_sample_n   => p_sample_n
      );
    end loop;
  end profile_tables;

  --------------------------------------------------------------------
  procedure clear_profile (
