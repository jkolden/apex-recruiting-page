    procedure preview(
        p_job_id          in  number,
        p_new_count       out number,
        p_changed_count   out number,
        p_unchanged_count out number
    ) is
        l_matched number;
    begin
        select count(*) into p_new_count
        from (
            select distinct vendorid
            from stg_fbx_supplier_hdr
            where job_id = p_job_id
        ) s
        where not exists (
            select 1 from fbx_fusion_supplier_hdr f where f.vendorid = s.vendorid
        );

        select count(*) into l_matched
        from (
            select distinct vendorid
            from stg_fbx_supplier_hdr
            where job_id = p_job_id
        ) s
        where exists (
            select 1 from fbx_fusion_supplier_hdr f where f.vendorid = s.vendorid
        );

        select count(*) into p_unchanged_count
        from (
            select
                vendorid,
                partyid,
                segment1,
                alternatenamepartyname,
                businessrelationship,
                incometaxid,
                organizationtypelookupcode,
                type1099,
                vendortypelookupcode
            from (
                select
                    s.*,
                    row_number() over (partition by vendorid order by rowid) rn
                from stg_fbx_supplier_hdr s
                where job_id = p_job_id
            )
            where rn = 1
            intersect
            select
                vendorid,
                partyid,
                segment1,
                alternatenamepartyname,
                businessrelationship,
                incometaxid,
                organizationtypelookupcode,
                type1099,
                vendortypelookupcode
            from fbx_fusion_supplier_hdr
        );

        p_changed_count := l_matched - p_unchanged_count;
    end preview;


