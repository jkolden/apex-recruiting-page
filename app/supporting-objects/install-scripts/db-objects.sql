  ) is
  begin
    if p_table_name is null then
      delete from column_profile;
    else
      delete from column_profile
      where  table_name = upper(trim(p_table_name));
    end if;
    commit;
  end clear_profile;

  --------------------------------------------------------------------
  -- refresh_view_crosswalk
  --   Parses views built as  SELECT <Fusion> UNION ALL SELECT <Lawson>
  --   and populates VIEW_COLUMN_CROSSWALK with column-level mappings.
  --------------------------------------------------------------------
  procedure refresh_view_crosswalk (
    p_view_name    in varchar2 default null,
    p_name_pattern in varchar2 default '%_V',
    p_owner        in varchar2 default user
  ) is
    v_text         clob;
    v_union_pos    number;
    v_fusion       clob;
    v_lawson       clob;
    v_sel_end      number;
    v_from_pos     number;
    v_list         clob;
    v_fusion_tbl   varchar2(400);
    v_lawson_tbl   varchar2(400);

    type t_arr is table of varchar2(4000) index by pls_integer;
    v_f  t_arr;
    v_l  t_arr;
    v_fc pls_integer;
    v_lc pls_integer;
    v_cnt pls_integer;

    v_alias  varchar2(128);
    v_fexpr  varchar2(4000);
    v_lexpr  varchar2(4000);

    ----------------------------------------------------------------
    -- split a SELECT-list on top-level commas (paren-aware only)
    ----------------------------------------------------------------
    procedure split_csv(p_txt clob, p_out out t_arr, p_cnt out pls_integer) is
      v_depth pls_integer := 0;
      v_start pls_integer := 1;
      v_n     pls_integer := 0;
      v_ch    char(1);
    begin
      for i in 1 .. nvl(length(p_txt), 0) loop
        v_ch := substr(p_txt, i, 1);
        if    v_ch = '(' then v_depth := v_depth + 1;
        elsif v_ch = ')' then v_depth := v_depth - 1;
        elsif v_ch = ',' and v_depth = 0 then
          v_n := v_n + 1;
          p_out(v_n) := substr(trim(substr(p_txt, v_start, i - v_start)), 1, 4000);
          v_start := i + 1;
        end if;
      end loop;
      v_n := v_n + 1;
      p_out(v_n) := substr(trim(substr(p_txt, v_start)), 1, 4000);
      p_cnt := v_n;
    end split_csv;

    ----------------------------------------------------------------
    -- strip trailing alias:  "expr AS alias" -> "expr"
    ----------------------------------------------------------------
    function strip_alias(p_item varchar2) return varchar2 is
      v_pos number;
    begin
      v_pos := regexp_instr(p_item, '\s[Aa][Ss]\s+\S+\s*$');
      if v_pos > 0 then return trim(substr(p_item, 1, v_pos - 1)); end if;
      return trim(p_item);
    end strip_alias;

    ----------------------------------------------------------------
    -- extract FROM-clause table names up to WHERE/GROUP/ORDER
    ----------------------------------------------------------------
    function get_tables(p_half clob) return varchar2 is
      v_from  number;
      v_chunk varchar2(4000);
      v_end   number;
    begin
      v_from := regexp_instr(p_half, '\sFROM\s', 1, 1, 0, 'i');
      if v_from = 0 then return null; end if;
      v_chunk := substr(trim(substr(p_half, v_from + 5, 1000)), 1, 4000);
      v_end   := regexp_instr(upper(v_chunk), '\s(WHERE|GROUP|ORDER|HAVING)\s');
      if v_end > 0 then v_chunk := substr(v_chunk, 1, v_end - 1); end if;
      return substr(regexp_replace(trim(v_chunk), '\s+', ' '), 1, 400);
    end get_tables;

  begin
    for rec in (
      select view_name, text
        from all_views
       where owner = upper(p_owner)
         and (  (p_view_name is not null and view_name = upper(p_view_name))
             or (p_view_name is null     and view_name like upper(p_name_pattern)))
       order by view_name
    ) loop
      -- strip comments (one-liners)
      v_text := regexp_replace(rec.text, '--.*$', '', 1, 0, 'm');
      v_text := regexp_replace(v_text, '/\*.*?\*/', ' ', 1, 0, 'n');

      -- find UNION ALL
      v_union_pos := regexp_instr(v_text, '\sUNION\s+ALL\s', 1, 1, 0, 'i');
      if v_union_pos = 0 then
        dbms_output.put_line('SKIP ' || rec.view_name || ': no UNION ALL');
        continue;
      end if;

      v_fusion := substr(v_text, 1, v_union_pos);
      v_lawson := regexp_replace(substr(v_text, v_union_pos), '^\s*UNION\s+ALL\s*', '', 1, 1, 'i');

      -- Fusion branch: SELECT list between SELECT and FROM
      v_sel_end  := instr(upper(v_fusion), 'SELECT') + 6;
      v_from_pos := regexp_instr(v_fusion, '\sFROM\s', 1, 1, 0, 'i');
      v_list     := substr(v_fusion, v_sel_end, v_from_pos - v_sel_end);
      split_csv(v_list, v_f, v_fc);
      v_fusion_tbl := get_tables(v_fusion);

      -- Lawson branch: same
      v_sel_end  := instr(upper(v_lawson), 'SELECT') + 6;
      v_from_pos := regexp_instr(v_lawson, '\sFROM\s', 1, 1, 0, 'i');
      v_list     := substr(v_lawson, v_sel_end, v_from_pos - v_sel_end);
      split_csv(v_list, v_l, v_lc);
      v_lawson_tbl := get_tables(v_lawson);

      v_cnt := greatest(nvl(v_fc, 0), nvl(v_lc, 0));

      for i in 1 .. v_cnt loop
        -- column name from data dictionary
        begin
          select column_name into v_alias
            from all_tab_columns
           where owner = upper(p_owner)
             and table_name = rec.view_name
             and column_id = i;
        exception when no_data_found then
          v_alias := 'COL_' || i;
        end;

        if v_f.exists(i) then v_fexpr := substr(strip_alias(v_f(i)), 1, 4000);
        else v_fexpr := null; end if;

        if v_l.exists(i) then v_lexpr := substr(strip_alias(v_l(i)), 1, 4000);
        else v_lexpr := null; end if;

        merge into view_column_crosswalk tgt
        using (
          select upper(rec.view_name) as vn, v_alias as cn, i as cp,
                 v_fexpr as fe, v_lexpr as le,
                 v_fusion_tbl as ft, v_lawson_tbl as lt
            from dual
        ) src
        on (tgt.view_name = src.vn and tgt.column_name = src.cn)
        when matched then
          update set
            tgt.col_position   = src.cp,
            tgt.fusion_source  = case when tgt.auto_parsed = 'Y' then src.fe else tgt.fusion_source end,
            tgt.lawson_source  = case when tgt.auto_parsed = 'Y' then src.le else tgt.lawson_source end,
            tgt.fusion_table   = src.ft,
            tgt.lawson_table   = src.lt,
            tgt.last_refreshed = systimestamp
          where tgt.auto_parsed = 'Y'
        when not matched then
          insert (view_name, column_name, col_position, fusion_source, lawson_source,
                  fusion_table, lawson_table, auto_parsed, last_refreshed)
          values (src.vn, src.cn, src.cp, src.fe, src.le,
                  src.ft, src.lt, 'Y', systimestamp);
      end loop;

      delete from view_column_crosswalk
       where view_name = upper(rec.view_name)
         and col_position > v_cnt;

      dbms_output.put_line('OK ' || rec.view_name || ' (' || v_cnt || ' cols)');
      v_f.delete;
      v_l.delete;
    end loop;

    commit;
  end refresh_view_crosswalk;

end col_profiler;
