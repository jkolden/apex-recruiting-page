OUTER APPLY (
  SELECT m1.load_type
  FROM bicc_loader_map m1
  WHERE m1.is_active = 'Y'
    AND m1.load_type IS NOT NULL
    AND m1.file_like IS NOT NULL
    AND lower(x.file_name) LIKE lower(m1.file_like)
  ORDER BY m1.priority NULLS LAST
  FETCH FIRST 1 ROW ONLY
) m;

