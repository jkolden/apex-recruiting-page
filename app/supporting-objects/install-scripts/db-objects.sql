create or replace package body pkg_benchmark as
    type t_timing is record (
        label varchar2(100),
        start_ts timestamp,
        end_ts timestamp,
        elapsed_seconds number
    );
    
    type t_timing_table is table of t_timing;
    g_timings t_timing_table := t_timing_table();
    
    procedure start_timer(p_label in varchar2) is
        l_timing t_timing;
    begin
        l_timing.label := p_label;
        l_timing.start_ts := systimestamp;
        g_timings.extend;
        g_timings(g_timings.last) := l_timing;
    end start_timer;
    
    procedure stop_timer(p_label in varchar2) is
    begin
        for i in reverse 1..g_timings.count loop
            if g_timings(i).label = p_label and g_timings(i).end_ts is null then
                g_timings(i).end_ts := systimestamp;
                g_timings(i).elapsed_seconds := 
                    extract(day from (g_timings(i).end_ts - g_timings(i).start_ts)) * 86400 +
                    extract(hour from (g_timings(i).end_ts - g_timings(i).start_ts)) * 3600 +
                    extract(minute from (g_timings(i).end_ts - g_timings(i).start_ts)) * 60 +
                    extract(second from (g_timings(i).end_ts - g_timings(i).start_ts));
                exit;
            end if;
        end loop;
    end stop_timer;
    
    procedure print_results is
    begin
        dbms_output.put_line(rpad('Label', 50) || rpad('Elapsed (sec)', 15) || 'Start Time');
        dbms_output.put_line(rpad('-', 50, '-') || rpad('-', 15, '-') || rpad('-', 30, '-'));
        
        for i in 1..g_timings.count loop
            dbms_output.put_line(
                rpad(g_timings(i).label, 50) || 
                rpad(to_char(g_timings(i).elapsed_seconds, '999,990.99'), 15) ||
                to_char(g_timings(i).start_ts, 'YYYY-MM-DD HH24:MI:SS')
            );
        end loop;
    end print_results;
    
    procedure clear_results is
    begin
        g_timings := t_timing_table();
    end clear_results;
end pkg_benchmark;
